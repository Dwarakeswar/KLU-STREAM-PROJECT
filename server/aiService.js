import { GoogleGenAI } from "@google/genai";
import { fetchTranscript } from "youtube-transcript-plus";

const apiKey = process.env.GEMINI_API_KEY;
const modelName = process.env.GEMINI_MODEL || "gemini-2.5-flash";
const ai = apiKey ? new GoogleGenAI({ apiKey }) : null;

function ensureAi() {
  if (!ai) {
    const err = new Error("GEMINI_API_KEY is not configured in server/.env");
    err.statusCode = 500;
    throw err;
  }
  return ai;
}

export async function getYouTubeTranscriptAndTitle({ videoId, videoUrl }) {
  let segments = [];
  let title = "";

  try {
    const data = await fetchTranscript(videoUrl || videoId, { videoDetails: true });
    if (Array.isArray(data)) {
      segments = data;
    } else if (data && typeof data === "object") {
      title = data.videoDetails?.title || data.title || "";
      if (Array.isArray(data.tracks) && data.tracks.length > 0) {
        const manual = data.tracks.find((t) => !t.isAutoGenerated);
        const chosen = manual || data.tracks[0];
        segments = chosen?.segments || data.segments || [];
      } else {
        segments = data.segments || [];
      }
    }
  } catch (err) {
    return {
      hasSubtitles: false,
      title,
      transcript: "",
      message:
        err?.message ||
        "Subtitles are not available for this YouTube video.",
    };
  }

  const transcript = segments
    .map((s) => String(s.text || "").replace(/\s+/g, " ").trim())
    .filter(Boolean)
    .join(" ");

  if (!transcript) {
    return {
      hasSubtitles: false,
      title,
      transcript: "",
      message: "No transcript text found for this YouTube video.",
    };
  }

  if (!title && videoUrl) {
    try {
      const res = await fetch(
        `https://www.youtube.com/oembed?url=${encodeURIComponent(videoUrl)}&format=json`
      );
      if (res.ok) {
        const meta = await res.json();
        title = meta?.title || "";
      }
    } catch {
      // Ignore oEmbed errors
    }
  }

  return {
    hasSubtitles: true,
    title: title || `YouTube Video (${videoId})`,
    transcript,
    message: "",
  };
}

export async function summarizeVideo({ videoId, videoUrl }) {
  const client = ensureAi();
  const captionResult = await getYouTubeTranscriptAndTitle({ videoId, videoUrl });

  if (!captionResult.hasSubtitles) {
    return {
      hasSubtitles: false,
      title: captionResult.title,
      transcript: "",
      summary: "",
      keyPoints: [],
      message: captionResult.message,
    };
  }

  const clippedTranscript = captionResult.transcript.slice(0, 50000);

  const prompt = `
Summarize this YouTube video based strictly on the transcript below.
Return ONLY valid JSON in this exact format:
{
  "summary": "A clear 3-4 sentence summary of the video.",
  "keyPoints": [
    "Important point 1",
    "Important point 2"
  ]
}

Video Title: ${captionResult.title}
Video URL: ${videoUrl}

Transcript:
${clippedTranscript}
`;

  const response = await client.models.generateContent({
    model: modelName,
    config: {
      responseMimeType: "application/json",
      temperature: 0.3,
    },
    contents: prompt,
  });

  const rawText = String(response.text || "").trim();
  try {
    const parsed = JSON.parse(rawText);
    return {
      hasSubtitles: true,
      title: captionResult.title,
      transcript: captionResult.transcript,
      summary: String(parsed.summary || "").trim(),
      keyPoints: Array.isArray(parsed.keyPoints)
        ? parsed.keyPoints.map(String).filter(Boolean).slice(0, 6)
        : [],
      message: "",
    };
  } catch {
    return {
      hasSubtitles: true,
      title: captionResult.title,
      transcript: captionResult.transcript,
      summary: rawText,
      keyPoints: [],
      message: "",
    };
  }
}

export async function discussVideo({
  videoTitle = "",
  videoUrl = "",
  summary = "",
  transcript = "",
  question = "",
  history = [],
}) {
  const client = ensureAi();
  const cleanQuestion = String(question || "").trim();

  if (!cleanQuestion) {
    const err = new Error("Please enter a question or message about the video.");
    err.statusCode = 400;
    throw err;
  }

  const chatHistory = Array.isArray(history)
    ? history
        .slice(-8)
        .map((m) => `${m.role === "user" ? "User" : "AI"}: ${String(m.text || "")}`)
        .join("\n")
    : "";

  const prompt = `
You are a helpful AI assistant discussing a YouTube video with the user.
Base your answers strictly on the video summary and transcript provided below. If something is not in the transcript, say so clearly instead of guessing.

Video Title: ${videoTitle || "YouTube Video"}
Video URL: ${videoUrl || ""}
Summary: ${summary || "N/A"}

Transcript:
${String(transcript || "").slice(0, 40000)}

${chatHistory ? `Recent Conversation:\n${chatHistory}\n` : ""}User: ${cleanQuestion}
`;

  const response = await client.models.generateContent({
    model: modelName,
    config: {
      temperature: 0.5,
    },
    contents: prompt,
  });

  return {
    reply: String(response.text || "").trim(),
  };
}